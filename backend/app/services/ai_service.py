"""
AI Service — Local LLM assistant via LM Studio.

All AI processing runs on the shop computer. The LLM is accessed through
LM Studio's OpenAI-compatible API (default: http://localhost:1234/v1).

Architecture:
  - Read-only data access: the AI can query any table but never writes
  - Tool-calling pattern: the LLM is given function descriptions and can
    request data fetches, which we execute and feed back into the conversation
  - Cached results: anomaly/prediction outputs are stored in ai_cached_results
  - Ephemeral conversations: chat history lives in-memory on the backend,
    keyed by a session token; nothing is persisted to disk

Security:
  - Zero cloud dependency — all traffic stays on localhost / LAN
  - All SQL generated by the AI is validated to be SELECT-only
  - The use_ai permission controls access
"""

