# ── Main AI Service ──────────────────────────────────────────────

class AiService:
    """Local AI assistant with read-only data access via LM Studio."""

    def __init__(self, db: aiosqlite.Connection) -> None:
        self.db = db
        self.db.row_factory = aiosqlite.Row

    async def _get_lm_studio_url(self) -> str:
        """Read LM Studio URL from app settings, falling back to default."""
        try:
            cursor = await self.db.execute(
                "SELECT value FROM settings WHERE key = 'ai_lm_studio_url'"
            )
            row = await cursor.fetchone()
            if row and row[0]:
                return row[0].rstrip("/")
        except Exception:
            pass
        return DEFAULT_LM_STUDIO_URL.rstrip("/")

    async def _is_feature_enabled(self, feature_key: str) -> bool:
        """Check if a specific AI feature is enabled in settings."""
        try:
            cursor = await self.db.execute(
                "SELECT value FROM settings WHERE key = ?", (feature_key,)
            )
            row = await cursor.fetchone()
            return row is not None and row[0] == "true"
        except Exception:
            return False

    async def _is_ai_enabled(self) -> bool:
        """Check if the master AI toggle is on."""
        return await self._is_feature_enabled("ai_enabled")

    async def check_connection(self) -> dict:
        """Test connectivity to LM Studio and return model info."""
        url = await self._get_lm_studio_url()
        try:
            async with httpx.AsyncClient(timeout=10.0) as client:
                resp = await client.get(f"{url}/models")
                if resp.status_code == 200:
                    data = resp.json()
                    models = data.get("data", [])
                    return {
                        "status": "connected",
                        "url": url,
                        "models": [m.get("id", "unknown") for m in models],
                        "model_count": len(models),
                    }
                return {"status": "error", "url": url, "error": f"HTTP {resp.status_code}"}
        except httpx.ConnectError:
            return {"status": "unreachable", "url": url, "error": "Cannot connect to LM Studio. Is it running?"}
        except Exception as exc:
            return {"status": "error", "url": url, "error": str(exc)}

    # ── Tool Execution ───────────────────────────────────────────

    async def _execute_tool(self, tool_name: str, arguments: dict) -> str:
        """Execute a read-only tool call and return results as formatted string."""
        builder = TOOL_QUERY_BUILDERS.get(tool_name)
        if not builder:
            return f"Unknown tool: {tool_name}"

        try:
            sql, args = builder(arguments)

            # Safety: verify query is SELECT-only
            normalized = sql.strip().upper()
            if not normalized.startswith("SELECT"):
                logger.warning("AI tried to run non-SELECT query: %s", sql[:100])
                return "Error: Only SELECT queries are allowed."

            # Block dangerous keywords
            dangerous = {"INSERT", "UPDATE", "DELETE", "DROP", "ALTER", "CREATE", "ATTACH", "DETACH"}
            tokens = set(re.findall(r'\b[A-Z]+\b', normalized))
            if tokens & dangerous:
                logger.warning("AI query contains dangerous keyword: %s", tokens & dangerous)
                return "Error: Query contains forbidden operations."

            cursor = await self.db.execute(sql, args)
            rows = await cursor.fetchall()

            if not rows:
                return "No results found."

            # Convert to list of dicts
            columns = [desc[0] for desc in cursor.description]
            results = [dict(zip(columns, row)) for row in rows]

            # Format as readable text (not raw JSON — LLMs do better with tables)
            if len(results) <= 10:
                # Table format for small results
                header = " | ".join(columns)
                separator = "-|-".join("-" * len(c) for c in columns)
                data_rows = []
                for r in results:
                    data_rows.append(" | ".join(str(r.get(c, "")) for c in columns))
                return f"Results ({len(results)} rows):\n{header}\n{separator}\n" + "\n".join(data_rows)
            else:
                # Summary for large results
                return f"Results ({len(results)} rows):\n" + json.dumps(results, indent=2, default=str)

        except Exception as exc:
            logger.exception("Tool execution error for %s", tool_name)
            return f"Error executing {tool_name}: {str(exc)}"

    # ── Chat / Ask ───────────────────────────────────────────────

    async def ask(
        self,
        question: str,
        conversation_history: list[dict] | None = None,
        page_context: str | None = None,
    ) -> dict:
        """Answer a natural language question using data + LLM.

        Returns: {"answer": str, "tool_calls_made": int, "model": str}
        """
        if not await self._is_ai_enabled():
            return {"answer": "AI is currently disabled. Enable it in Settings → AI Config.", "tool_calls_made": 0, "model": "none"}

        url = await self._get_lm_studio_url()

        # Build messages
        messages = [{"role": "system", "content": SYSTEM_PROMPT}]

        # Add page context if available
        if page_context:
            ctx_msg = f"The user is currently viewing the '{page_context}' section of the application."
            messages.append({"role": "system", "content": ctx_msg})

        # Add conversation history (last 10 exchanges max)
        if conversation_history:
            for msg in conversation_history[-20:]:
                messages.append(msg)

        messages.append({"role": "user", "content": question})

        tool_calls_made = 0
        max_tool_rounds = 5  # Prevent infinite tool-calling loops
        model_used = "unknown"

        async with httpx.AsyncClient(timeout=REQUEST_TIMEOUT) as client:
            for _round in range(max_tool_rounds):
                try:
                    resp = await client.post(
                        f"{url}/chat/completions",
                        json={
                            "messages": messages,
                            "tools": TOOL_DEFINITIONS,
                            "tool_choice": "auto",
                            "temperature": 0.3,
                            "max_tokens": 2048,
                        },
                    )
                    resp.raise_for_status()
                    data = resp.json()
                except httpx.ConnectError:
                    return {
                        "answer": "Cannot reach LM Studio. Make sure it's running and a model is loaded.",
                        "tool_calls_made": tool_calls_made,
                        "model": "unreachable",
                    }
                except Exception as exc:
                    logger.exception("LM Studio request failed")
                    return {
                        "answer": f"AI request failed: {str(exc)}",
                        "tool_calls_made": tool_calls_made,
                        "model": "error",
                    }

                choice = data.get("choices", [{}])[0]
                message = choice.get("message", {})
                model_used = data.get("model", "unknown")

                # Check if the LLM wants to call tools
                tool_calls = message.get("tool_calls")
                if tool_calls:
                    # Add the assistant's tool-call message
                    messages.append(message)

                    for tc in tool_calls:
                        fn_name = tc["function"]["name"]
                        try:
                            fn_args = json.loads(tc["function"]["arguments"])
                        except (json.JSONDecodeError, KeyError):
                            fn_args = {}

                        logger.info("AI tool call: %s(%s)", fn_name, fn_args)
                        result = await self._execute_tool(fn_name, fn_args)
                        tool_calls_made += 1

                        messages.append({
                            "role": "tool",
                            "tool_call_id": tc["id"],
                            "content": result,
                        })

                    # Continue loop — LLM will process tool results
                    continue

                # No tool calls — we have the final answer
                answer = message.get("content", "I wasn't able to generate a response.")
                return {
                    "answer": answer,
                    "tool_calls_made": tool_calls_made,
                    "model": model_used,
                }

        return {
            "answer": "AI reached maximum tool-calling rounds without producing a final answer.",
            "tool_calls_made": tool_calls_made,
            "model": model_used,
        }

