def _build_schedule_query(params: dict) -> tuple[str, list]:
    """Build SELECT query for scheduling (daily dispatch)."""
    sql = """
        SELECT s.id, s.scheduled_date, u.display_name AS employee,
               j.job_name AS job_name, j.job_number, s.start_time, s.end_time,
               s.status, s.notes
        FROM scheduling s
        JOIN users u ON u.id = s.user_id
        JOIN jobs j ON j.id = s.job_id
        WHERE 1=1
    """
    args: list = []
    if params.get("date"):
        sql += " AND s.scheduled_date = ?"
        args.append(params["date"])
    if params.get("week_of"):
        end = (datetime.strptime(params["week_of"], "%Y-%m-%d") + timedelta(days=6)).strftime("%Y-%m-%d")
        sql += " AND s.scheduled_date BETWEEN ? AND ?"
        args.extend([params["week_of"], end])
    if params.get("employee_id"):
        sql += " AND s.user_id = ?"
        args.append(params["employee_id"])
    if params.get("job_id"):
        sql += " AND s.job_id = ?"
        args.append(params["job_id"])
    sql += " ORDER BY s.scheduled_date, s.start_time LIMIT 100"
    return sql, args


def _build_costs_query(params: dict) -> tuple[str, list]:
    """Build SELECT query for cost data."""
    period = params.get("period", "this_month")
    now = datetime.now(timezone.utc)

    if period == "this_week":
        start = (now - timedelta(days=now.weekday())).strftime("%Y-%m-%d")
    elif period == "last_week":
        start = (now - timedelta(days=now.weekday() + 7)).strftime("%Y-%m-%d")
    elif period == "last_month":
        first_this = now.replace(day=1)
        last_prev = first_this - timedelta(days=1)
        start = last_prev.replace(day=1).strftime("%Y-%m-%d")
    elif period == "ytd":
        start = now.strftime("%Y-01-01")
    else:  # this_month
        start = now.strftime("%Y-%m-01")

    if params.get("job_id"):
        sql = """
            SELECT j.job_name AS job_name, j.job_number,
                   j.budget_labor, j.budget_materials,
                   COALESCE(SUM(le.regular_hours), 0) AS total_regular_hours,
                   COALESCE(SUM(le.overtime_hours), 0) AS total_overtime_hours,
                   COUNT(DISTINCT le.user_id) AS unique_workers
            FROM jobs j
            LEFT JOIN labor_entries le ON le.job_id = j.id AND le.clock_in >= ?
            WHERE j.id = ?
            GROUP BY j.id
        """
        args = [start, params["job_id"]]
    else:
        sql = """
            SELECT j.job_name AS job_name, j.job_number,
                   j.budget_labor, j.budget_materials,
                   COALESCE(SUM(le.regular_hours), 0) AS total_regular_hours,
                   COALESCE(SUM(le.overtime_hours), 0) AS total_overtime_hours,
                   COUNT(DISTINCT le.user_id) AS unique_workers
            FROM jobs j
            LEFT JOIN labor_entries le ON le.job_id = j.id AND le.clock_in >= ?
            WHERE j.status = 'active'
            GROUP BY j.id
            ORDER BY total_regular_hours DESC
            LIMIT 20
        """
        args = [start]
    return sql, args


def _build_employees_query(params: dict) -> tuple[str, list]:
    """Build SELECT query for employee info."""
    sql = """
        SELECT u.id, u.display_name, u.username, u.is_active,
               GROUP_CONCAT(DISTINCT h.name) AS hats
        FROM users u
        LEFT JOIN user_hats uh ON uh.user_id = u.id
        LEFT JOIN hats h ON h.id = uh.hat_id
        WHERE 1=1
    """
    args: list = []
    if params.get("employee_id"):
        sql += " AND u.id = ?"
        args.append(params["employee_id"])
    if params.get("search"):
        sql += " AND u.display_name LIKE ?"
        args.append(f"%{params['search']}%")
    if params.get("active_only", True):
        sql += " AND u.is_active = 1"
    sql += " GROUP BY u.id ORDER BY u.display_name LIMIT 50"
    return sql, args


