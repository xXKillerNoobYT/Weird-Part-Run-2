def _build_labor_query(params: dict) -> tuple[str, list]:
    """Build SELECT query for labor entries."""
    sql = """
        SELECT le.id, u.display_name AS employee, j.job_name AS job_name, j.job_number,
               le.clock_in, le.clock_out, le.regular_hours, le.overtime_hours, le.status
        FROM labor_entries le
        JOIN users u ON u.id = le.user_id
        JOIN jobs j ON j.id = le.job_id
        WHERE 1=1
    """
    args: list = []
    if params.get("employee_id"):
        sql += " AND le.user_id = ?"
        args.append(params["employee_id"])
    if params.get("employee_name"):
        sql += " AND u.display_name LIKE ?"
        args.append(f"%{params['employee_name']}%")
    if params.get("job_id"):
        sql += " AND le.job_id = ?"
        args.append(params["job_id"])
    if params.get("start_date"):
        sql += " AND le.clock_in >= ?"
        args.append(params["start_date"])
    if params.get("end_date"):
        sql += " AND le.clock_in <= ?"
        args.append(params["end_date"] + "T23:59:59")
    sql += " ORDER BY le.clock_in DESC LIMIT 100"
    return sql, args


def _build_jobs_query(params: dict) -> tuple[str, list]:
    """Build SELECT query for jobs."""
    sql = """
        SELECT j.id, j.job_number, j.job_name, j.status, j.address_line1 AS address,
               j.budget_labor, j.budget_materials, j.created_at
        FROM jobs j
        WHERE 1=1
    """
    args: list = []
    if params.get("job_id"):
        sql += " AND j.id = ?"
        args.append(params["job_id"])
    if params.get("status"):
        sql += " AND j.status = ?"
        args.append(params["status"])
    if params.get("search"):
        sql += " AND (j.job_name LIKE ? OR j.job_number LIKE ?)"
        args.extend([f"%{params['search']}%", f"%{params['search']}%"])
    sql += " ORDER BY j.created_at DESC LIMIT 50"
    return sql, args


def _build_stock_query(params: dict) -> tuple[str, list]:
    """Build SELECT query for stock levels."""
    sql = """
        SELECT s.id, p.description AS part_name, pc.name AS category,
               s.quantity_on_hand, s.minimum_stock, s.bin_location,
               s.quantity_on_hand - COALESCE(s.minimum_stock, 0) AS surplus
        FROM stock s
        JOIN parts p ON p.id = s.part_id
        LEFT JOIN part_types pt ON pt.id = p.part_type_id
        LEFT JOIN part_styles ps ON ps.id = pt.style_id
        LEFT JOIN part_categories pc ON pc.id = ps.category_id
        WHERE 1=1
    """
    args: list = []
    if params.get("part_id"):
        sql += " AND s.part_id = ?"
        args.append(params["part_id"])
    if params.get("category"):
        sql += " AND pc.name LIKE ?"
        args.append(f"%{params['category']}%")
    if params.get("low_stock_only"):
        sql += " AND s.quantity_on_hand < COALESCE(s.minimum_stock, 0)"
    if params.get("search"):
        sql += " AND p.description LIKE ?"
        args.append(f"%{params['search']}%")
    sql += " ORDER BY surplus ASC LIMIT 100"
    return sql, args


def _build_usage_query(params: dict) -> tuple[str, list]:
    """Build SELECT query for parts usage (stock movements)."""
    days = params.get("days", 30)
    cutoff = (datetime.now(timezone.utc) - timedelta(days=days)).strftime("%Y-%m-%d")

    sql = """
        SELECT sm.id, p.description AS part_name, j.job_name AS job_name,
               sm.quantity, sm.movement_type, sm.created_at,
               u.display_name AS moved_by
        FROM stock_movements sm
        JOIN parts p ON p.id = sm.part_id
        LEFT JOIN jobs j ON j.id = sm.job_id
        LEFT JOIN users u ON u.id = sm.user_id
        WHERE sm.created_at >= ?
    """
    args: list[Any] = [cutoff]
    if params.get("job_id"):
        sql += " AND sm.job_id = ?"
        args.append(params["job_id"])
    if params.get("part_id"):
        sql += " AND sm.part_id = ?"
        args.append(params["part_id"])
    if params.get("start_date"):
        sql = sql.replace(f"sm.created_at >= ?", "sm.created_at >= ?")
        args[0] = params["start_date"]
    if params.get("end_date"):
        sql += " AND sm.created_at <= ?"
        args.append(params["end_date"] + "T23:59:59")
    sql += " ORDER BY sm.created_at DESC LIMIT 200"
    return sql, args


